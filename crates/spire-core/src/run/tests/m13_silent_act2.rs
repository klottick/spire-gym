use super::super::*;
use crate::{combat::{CombatAction, Outcome, rng::Partition}, content::{Character, CardId, EncounterId, EventId, PotionId, RelicId}};

fn profile() -> CreationProfile {
    let mut profile = CreationProfile::experienced();
    profile.neow_eligible = false;
    profile.seen_bosses[0] = vec!["Hexaghost", "SlimeBoss"];
    profile.seen_bosses[1] = vec!["Automaton", "Collector"];
    profile
}

fn run() -> Run {
    Run::new_room_scenario(
        RunConfig { character: Character::Silent, ascension: 0 },
        profile(),
        RunRng::new([7; 32], Partition::Test, 0),
        RoomScenario::M13SilentAct2,
    ).unwrap()
}

fn choose(run: &mut Run, kind: RoomChoiceKind) -> RunTransition {
    let room = run.decision().unwrap().room.unwrap();
    let row = room.choices.iter().find(|row| row.kind == kind && row.status == RoomChoiceStatus::Offered)
        .unwrap_or_else(|| panic!("expected offered {kind:?}, actual {room:?}"));
    run.step(&GameAction::Choose(row.id)).unwrap()
}

// A bounded room-owner fixture: the map is generated by the shared Act2 map
// owner and every exercised room is entered through the public Run action.
fn act2_run(gold: u32) -> Run {
    let mut run = run();
    choose(&mut run, RoomChoiceKind::NeowLament);
    run.state.gold = gold;
    let mut rng = run.state.rng.clone();
    let mut map = super::super::map::generate(2, &mut rng, super::super::map::MapEligibility::from_run(&run.state)).unwrap();
    for node in &mut map.nodes { node.floor += 17; }
    map.boss_icon = Some(EncounterId::Champ);
    run.state.act = 2;
    run.state.floor = 17;
    run.state.room = "Map";
    run.state.map = Some(map);
    run.state.rng = rng;
    let room = run.state.room_loop.as_mut().unwrap();
    room.act1 = None;
    room.act2 = Some(Default::default());
    room.act2_boss_order = Some(vec![EncounterId::Champ]);
    room.transition = Some(ActTransition {
        from: 1, to: 2, floor: 17, reset_applied: true, heal_applied: true, initialized: true,
    });
    room.screen = RoomView { kind: RoomViewKind::Map, choices: vec![] };
    run.candidates.clear();
    run
}

fn enter_question(run: &mut Run) {
    let map = run.state.map.as_mut().unwrap();
    let target = map.nodes.iter().find(|node| node.kind == MapNodeKind::Question && !node.visited
        && map.nodes.iter().any(|previous| previous.edges.contains(&node.id))).unwrap().id;
    let previous = map.nodes.iter_mut().find(|node| node.edges.contains(&target)).unwrap();
    previous.visited = true;
    let floor = previous.floor;
    let previous_id = previous.id;
    run.state.floor = floor;
    map.current = Some(previous_id);
    run.step(&GameAction::Move(target)).unwrap();
}

fn act2_boss_reward(run: &mut Run) {
    let map = run.state.map.as_mut().unwrap();
    let boss = map.nodes.iter_mut().find(|node| node.kind == MapNodeKind::Boss && node.floor == 33).unwrap();
    boss.visited = true;
    boss.revealed = true;
    boss.encounter = Some(EncounterId::Champ);
    run.state.floor = 33;
    map.current = Some(boss.id);
    let mut next = run.next_choice;
    let card_rows = vec![
        (RoomChoiceKind::Card { id: CardId::Nightmare, upgrades: 0 }, None),
        (RoomChoiceKind::Skip, None),
    ];
    let cards = rooms::view(&mut next, RoomViewKind::CardReward, card_rows).unwrap();
    let screen = rooms::view(&mut next, RoomViewKind::Rewards, vec![
        (RoomChoiceKind::CardReward, None), (RoomChoiceKind::Proceed, None),
    ]).unwrap();
    run.next_choice = next;
    let room = run.state.room_loop.as_mut().unwrap();
    room.screen = screen;
    room.active_rewards = Some(rooms::rewards::CapturedRewards {
        cards,
        return_to: rooms::rewards::RewardReturn::BossTreasure,
    });
    choose(run, RoomChoiceKind::CardReward);
    choose(run, RoomChoiceKind::Skip);
    choose(run, RoomChoiceKind::Proceed);
}

fn enter_elite(run: &mut Run) {
    let map = run.state.map.as_mut().unwrap();
    let target = map.nodes.iter().find(|node| node.kind == MapNodeKind::Elite && !node.visited
        && map.nodes.iter().any(|previous| previous.edges.contains(&node.id))).unwrap().id;
    let previous = map.nodes.iter_mut().find(|node| node.edges.contains(&target)).unwrap();
    previous.visited = true;
    let floor = previous.floor;
    let previous_id = previous.id;
    run.state.floor = floor;
    map.current = Some(previous_id);
    run.step(&GameAction::Move(target)).unwrap();
}

fn finish_floor26_treasure(run: &mut Run) -> RoomViewKind {
    let map = run.state.map.as_mut().unwrap();
    let treasure = map.nodes.iter_mut().find(|node| node.kind == MapNodeKind::Treasure && node.floor == 26).unwrap();
    treasure.visited = true;
    map.current = Some(treasure.id);
    run.state.floor = 26;
    run.state.room_loop.as_mut().unwrap().screen = RoomView { kind: RoomViewKind::Treasure, choices: vec![] };
    rooms::finish(run).unwrap();
    run.decision().unwrap().room.unwrap().kind
}


