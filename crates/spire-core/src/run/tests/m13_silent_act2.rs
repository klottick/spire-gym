fn m13_profile_and_full_act2_route_resolve_real_boss_reward_children() {
    assert!(Run::new_room_scenario(RunConfig { character: Character::Ironclad, ascension: 0 }, profile(), RunRng::new([1; 32], Partition::Test, 0), RoomScenario::M13SilentAct2).is_err());
    assert!(Run::new_room_scenario(RunConfig { character: Character::Silent, ascension: 1 }, profile(), RunRng::new([1; 32], Partition::Test, 0), RoomScenario::M13SilentAct2).is_err());
    let mut long_neow = profile();
    long_neow.neow_eligible = true;
    assert!(Run::new_room_scenario(RunConfig { character: Character::Silent, ascension: 0 }, long_neow, RunRng::new([1; 32], Partition::Test, 0), RoomScenario::M13SilentAct2).is_err());

    let mut normal = run();
    assert_eq!((normal.state.hp, normal.state.max_hp, normal.state.gold), (70, 70, 99));
    assert_eq!(normal.state.deck.len(), 12);
    assert!(normal.public_map().is_none());
    choose(&mut normal, RoomChoiceKind::NeowLament);
    assert_eq!(normal.public_map().unwrap().boss, Some(EncounterId::Guardian));
    assert_eq!(normal.decision().unwrap().content_profile, Some(RoomScenario::M13SilentAct2));

    let mut catalog = run();
    for &id in M12_SILENT_ACT1_CARDS {
        mutations::obtain_card(&mut catalog.state, id, 0).unwrap();
    }
    let before = catalog.clone();
    assert!(mutations::obtain_card(&mut catalog.state, CardId::Strike, 0).is_err());
    assert_eq!(catalog, before);

    let mut act1_reward = run();
    choose(&mut act1_reward, RoomChoiceKind::NeowLament);
    let first_move = act1_reward.decision().unwrap().candidates.into_iter()
        .find(|candidate| matches!(candidate.action, GameAction::Move(_))).unwrap().action;
    act1_reward.step(&first_move).unwrap();
    let active = act1_reward.state.active_combat.as_ref().unwrap();
    let record = CombatRecord { visit: active.visit, encounter: active.encounter, outcome: Outcome::Victory };
    let prepared = rooms::rewards::prepare_combat(&act1_reward, &record).unwrap().unwrap();
    rooms::rewards::commit_combat(&mut act1_reward, prepared);
    assert_eq!(act1_reward.state.room_loop.as_ref().unwrap().screen.choices.iter()
        .find(|row| matches!(row.kind, RoomChoiceKind::Potion(_))).unwrap().kind, RoomChoiceKind::Potion(PotionId::FirePotion));
    let card_rows = &act1_reward.state.room_loop.as_ref().unwrap().active_rewards.as_ref().unwrap().cards.choices;
    assert_eq!(card_rows.iter().filter_map(|row| match row.kind { RoomChoiceKind::Card { id, .. } => Some(id), _ => None }).collect::<Vec<_>>(),
        vec![CardId::PoisonedStab, CardId::Backflip, CardId::BladeDance]);

    let mut act1_shop = run();
    choose(&mut act1_shop, RoomChoiceKind::NeowLament);
    let mut next_choice = act1_shop.next_choice;
    let mut shop_rng = act1_shop.state.rng.clone();
    let first_shop = rooms::shop::screen_with_rng_at(&act1_shop, &mut next_choice, &mut shop_rng, (1, 4, NodeId(7))).unwrap();
    assert_eq!(first_shop.choices.iter().filter_map(|row| match row.kind { RoomChoiceKind::Card { id, .. } => Some(id), _ => None }).collect::<Vec<_>>(),
        vec![CardId::QuickSlash, CardId::Reflex, CardId::Catalyst]);
    assert!(first_shop.choices.iter().any(|row| row.kind == RoomChoiceKind::Potion(PotionId::DexterityPotion)));
    act1_shop.state.room_loop.as_mut().unwrap().act1.as_mut().unwrap().shop_visits = 1;
    let later_shop = rooms::shop::screen_with_rng_at(&act1_shop, &mut next_choice, &mut shop_rng, (1, 5, NodeId(8))).unwrap();
    assert_eq!(later_shop.choices.iter().filter_map(|row| match row.kind { RoomChoiceKind::Card { id, .. } => Some(id), _ => None }).collect::<Vec<_>>(),
        vec![CardId::Deflect, CardId::Tactician, CardId::Nightmare]);
    assert!(later_shop.choices.iter().any(|row| row.kind == RoomChoiceKind::Potion(PotionId::FirePotion)));

    let mut act2 = act2_run(99);
    let map = act2.public_map().unwrap();
    assert_eq!((map.act, map.boss), (2, Some(EncounterId::Champ)));
    assert_eq!(act2.decision().unwrap().content_profile, Some(RoomScenario::M13SilentAct2));
    let boss = act2.state.map.as_ref().unwrap().nodes.iter().find(|node| node.kind == MapNodeKind::Boss && node.floor == 33).unwrap().id;
    assert_eq!(rooms::act2::capture_room(&act2.state, boss).unwrap().encounter, Some(EncounterId::Champ));
    let reachable = map.nodes.iter().filter(|node| node.floor == 18).map(|node| node.id).any(|start| {
        let mut frontier = vec![start];
        let mut seen = Vec::new();
        while let Some(id) = frontier.pop() {
            if id == boss { return true; }
            if seen.contains(&id) { continue; }
            seen.push(id);
            if let Some(node) = map.nodes.iter().find(|node| node.id == id) { frontier.extend(node.edges.iter().copied()); }
        }
        false
    });
    assert!(reachable, "a generated Act2 entry must lead through visible edges to floor 33");

    let mut m13_mid = act2.clone();
    assert_eq!(finish_floor26_treasure(&mut m13_mid), RoomViewKind::Map);
    let mut m7_mid = act2.clone();
    m7_mid.state.room_loop.as_mut().unwrap().scenario = RoomScenario::M7Act2Captured;
    assert_eq!(finish_floor26_treasure(&mut m7_mid), RoomViewKind::Map);
    let mut m6_mid = act2.clone();
    m6_mid.state.room_loop.as_mut().unwrap().scenario = RoomScenario::M6Act2Prefix;
    assert_eq!(finish_floor26_treasure(&mut m6_mid), RoomViewKind::Act2PrefixComplete);
    let m12 = Run::new_room_scenario(
        RunConfig { character: Character::Silent, ascension: 0 }, profile(),
        RunRng::new([7; 32], Partition::Test, 0), RoomScenario::M12SilentAct1,
    ).unwrap();
    assert!(!rooms::uses_captured_act2(&m12.state), "M12 retains its Act2Ready cutoff");

    act2_boss_reward(&mut act2);
    let chest = act2.decision().unwrap().room.unwrap();
    assert_eq!(chest.kind, RoomViewKind::BossTreasure);
    choose(&mut act2, RoomChoiceKind::OpenChest);
    let offers = act2.decision().unwrap().room.unwrap();
    assert!(offers.choices.iter().any(|row| row.kind == RoomChoiceKind::Relic(RelicId::EmptyCage) && row.status == RoomChoiceStatus::Offered));
    assert!(offers.choices.iter().any(|row| row.kind == RoomChoiceKind::Relic(RelicId::SlaversCollar) && row.status == RoomChoiceStatus::Offered));
    assert!(!offers.choices.iter().any(|row| row.kind == RoomChoiceKind::Relic(RelicId::BlackBlood) && row.status == RoomChoiceStatus::Offered));
    choose(&mut act2, RoomChoiceKind::Relic(RelicId::SlaversCollar));
    choose(&mut act2, RoomChoiceKind::Proceed);
    let ready = act2.decision().unwrap();
    assert_eq!((ready.act, ready.floor, ready.terminal), (3, 34, None));
    assert_eq!(ready.room.unwrap().kind, RoomViewKind::Act3Ready);
    assert!(ready.candidates.is_empty());
    let act3_map = act2.public_map().unwrap();
    assert_eq!(act3_map.act, 3);
    assert!(matches!(act3_map.boss, Some(EncounterId::AwakenedOne | EncounterId::DonuAndDeca | EncounterId::TimeEater)));
    assert!(act2.state.room_loop.as_ref().unwrap().act3.is_none());

    let mut already_owned = act2_run(99);
    already_owned.state.relics.push(RelicId::SlaversCollar);
    act2_boss_reward(&mut already_owned);
    choose(&mut already_owned, RoomChoiceKind::OpenChest);
    let offers = already_owned.decision().unwrap().room.unwrap();
    assert!(offers.choices.iter().any(|row| row.kind == RoomChoiceKind::Relic(RelicId::SlaversCollar) && row.status == RoomChoiceStatus::Disabled));
    assert!(offers.choices.iter().any(|row| row.kind == RoomChoiceKind::Relic(RelicId::EmptyCage) && row.status == RoomChoiceStatus::Offered));
}

#[test]
fn m13_act2_questions_publish_ancient_writing_then_gold_gated_joust_or_purifier() {
    let mut rich = act2_run(99);
    let green_basics = rich.state.deck.iter().filter(|card| matches!(card.id, CardId::StrikeGreen | CardId::DefendGreen)).count();
    enter_question(&mut rich);
    assert_eq!(rich.decision().unwrap().room.unwrap().kind, RoomViewKind::Event(EventId::AncientWriting));
    choose(&mut rich, RoomChoiceKind::AncientSimplicity);
    assert_eq!(rich.state.deck.iter().filter(|card| matches!(card.id, CardId::StrikeGreen | CardId::DefendGreen) && card.upgrades == 1).count(), green_basics);
    choose(&mut rich, RoomChoiceKind::Leave);
    enter_question(&mut rich);
    assert_eq!(rich.decision().unwrap().room.unwrap().kind, RoomViewKind::Event(EventId::Joust));
    assert!(rich.state.gold >= 50);

    let mut poor = act2_run(49);
    enter_question(&mut poor);
    choose(&mut poor, RoomChoiceKind::AncientSimplicity);
    choose(&mut poor, RoomChoiceKind::Leave);
    enter_question(&mut poor);
    assert_eq!(poor.decision().unwrap().room.unwrap().kind, RoomViewKind::Event(EventId::Purifier));
    assert!(poor.state.gold < 50);
}

